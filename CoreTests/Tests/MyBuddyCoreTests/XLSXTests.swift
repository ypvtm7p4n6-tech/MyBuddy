final class XLSXTests: XCTestCase {

    private func read(_ data: Data, _ name: String = "test.xlsx") throws -> SpreadsheetWorkbook {
        try SpreadsheetReader.read(data, fileName: name)
    }

    private func assertError(_ data: Data, name: String, _ expected: SpreadsheetError,
                             file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertThrowsError(try SpreadsheetReader.read(data, fileName: name), file: file, line: line) { error in
            XCTAssertEqual(error as? SpreadsheetError, expected, file: file, line: line)
        }
    }

    // MARK: Werkbladen

    func testReadsAllSheetsWithNamesAndHiddenFlag() throws {
        let book = try read(XLSXFixtures.typed)
        XCTAssertEqual(book.tables.map(\.name), ["Gemengd", "Voorvoegsel", "Verborgen"])
        XCTAssertEqual(book.tables.map(\.isHidden), [false, false, true])
        XCTAssertEqual(book.tables[2].cell(0, 0), .text("Geheim"))
        XCTAssertEqual(book.fileName, "test.xlsx")
    }

    func testMonthsWorkbookKeepsHiddenSheetFlag() throws {
        let book = try read(XLSXFixtures.months)
        XCTAssertEqual(book.tables.map(\.name), ["Begroting 2026", "Lijsten"])
        XCTAssertEqual(book.tables.map(\.isHidden), [false, true])
    }

    // MARK: Celsoorten

    func testSharedStringsRichTextAndPhoneticRuns() throws {
        let sheet = try read(XLSXFixtures.typed).tables[0]
        XCTAssertEqual(sheet.cell(0, 0), .text("Tekst"))
        // Twee tekststukken worden aan elkaar gezet; de uitspraakhulp (rPh) telt niet mee.
        XCTAssertEqual(sheet.cell(0, 1), .text("Vaste lasten"))
        // Spaties blijven in de cel staan, de leesfuncties knippen ze weg.
        XCTAssertEqual(sheet.cell(0, 2), .text("  met spaties  "))
        XCTAssertEqual(sheet.cell(0, 2).trimmedText, "met spaties")
        XCTAssertEqual(sheet.cell(0, 3), .text("Caf\u{00E9} & bar"))
        // Een lege gedeelde tekst is een lege cel.
        XCTAssertEqual(sheet.cell(0, 4), .empty)
    }

    func testRichTextWrittenByOpenpyxl() throws {
        let sheet = try read(XLSXFixtures.rich).tables[0]
        XCTAssertEqual(sheet.cell(0, 0), .text("Vaste lasten"))
        XCTAssertEqual(sheet.cell(1, 0), .text("Huur"))
        XCTAssertEqual(sheet.cell(1, 1), .number(900))
    }

    func testNumbersBooleansAndDates() throws {
        let sheet = try read(XLSXFixtures.typed).tables[0]
        XCTAssertEqual(sheet.cell(1, 0), .number(1234.5))
        XCTAssertEqual(sheet.cell(1, 1), .bool(true))
        XCTAssertEqual(sheet.cell(1, 2), .bool(false))
        // Serienummer 46303 is 8 oktober 2026 (ingebouwde datumopmaak 14).
        XCTAssertEqual(sheet.cell(1, 3), .date(SheetDate(year: 2026, month: 10, day: 8)))
        // Eigen opmaak dd-mm-yyyy; het tijdgedeelte (.75 = 18:00) valt weg.
        XCTAssertEqual(sheet.cell(1, 4), .date(SheetDate(year: 2026, month: 10, day: 8)))
        XCTAssertEqual(sheet.cell(1, 3).displayText, "08-10-2026")
        // 61 is de eerste dag na het niet-bestaande 29 februari 1900.
        XCTAssertEqual(sheet.cell(5, 3), .date(SheetDate(year: 1900, month: 3, day: 1)))
        XCTAssertEqual(sheet.cell(5, 1), .number(7))
    }

    func testPercentagesAndOtherNumberFormatsStayNumbers() throws {
        let sheet = try read(XLSXFixtures.typed).tables[0]
        // Opmaak 10 (0,00%): 0,21 is 21%.
        XCTAssertEqual(sheet.cell(2, 0), .percent(0.21))
        XCTAssertEqual(sheet.cell(2, 0).displayText, "21%")
        // Eigen opmaak 0.0"d": de "d" staat tussen aanhalingstekens en maakt er geen datum van.
        XCTAssertEqual(sheet.cell(3, 2), .number(5))
        // Opmaak 4 (#,##0.00) blijft een getal.
        XCTAssertEqual(sheet.cell(3, 3), .number(12.5))
    }

    func testInlineStringsAndFormulaCachedValues() throws {
        let sheet = try read(XLSXFixtures.typed).tables[0]
        XCTAssertEqual(sheet.cell(2, 1), .text("Inline"))
        XCTAssertEqual(sheet.cell(2, 2), .text("Rijk inline"))
        // Formules: de gecachte waarde (<v>) telt, tekst of getal.
        XCTAssertEqual(sheet.cell(2, 3), .text("1234.5x"))
        XCTAssertEqual(sheet.cell(2, 4), .number(2469))
        // Een formule zonder gecachte waarde en een foutwaarde (#DEEL/0!) zijn geen gegevens.
        XCTAssertEqual(sheet.cell(3, 0), .empty)
        XCTAssertEqual(sheet.cell(3, 1), .empty)
    }

