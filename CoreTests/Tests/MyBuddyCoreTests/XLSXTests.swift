    func testCivilDayConversionAgainstKnownDays() {
        // Dagnummers vanaf 1 januari 1970, uitgerekend met Python.
        XCTAssertEqual(SheetDate(year: 2026, month: 10, day: 8).daysSince1970, 20_734)
        XCTAssertEqual(SheetDate(year: 1900, month: 1, day: 1).daysSince1970, -25_567)
        XCTAssertEqual(SheetDate(year: 1904, month: 1, day: 1).daysSince1970, -24_107)
        XCTAssertEqual(SheetDate(year: 1970, month: 1, day: 1).daysSince1970, 0)
        XCTAssertEqual(SheetDate(daysSince1970: 20_734), SheetDate(year: 2026, month: 10, day: 8))
        // Schrikkeljaar: 2028-02-29 bestaat, 2100-02-29 niet.
        XCTAssertEqual(SheetDate(year: 2028, month: 3, day: 1).daysSince1970 - SheetDate(year: 2028, month: 2, day: 28).daysSince1970, 2)
        XCTAssertEqual(SheetDate(year: 2100, month: 3, day: 1).daysSince1970 - SheetDate(year: 2100, month: 2, day: 28).daysSince1970, 1)
        // Heen en terug over een lange reeks dagen.
        for days in stride(from: -30_000, through: 60_000, by: 997) {
            let date = SheetDate(daysSince1970: days)
            XCTAssertEqual(date.daysSince1970, days)
        }
    }

